-- Description: Creates user_roles and machine_assignments tables for RBAC

-- Create app_role enum for user roles
CREATE TYPE public.app_role AS ENUM ('admin', 'operator');

-- Create user_roles table
-- Stores the role for each user in the system
CREATE TABLE public.user_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  role public.app_role NOT NULL DEFAULT 'operator',
  created_at timestamptz DEFAULT now(),
  UNIQUE (user_id)
);

-- Add comments for documentation
COMMENT ON TABLE public.user_roles IS 'Stores user roles for RBAC (admin/operator)';
COMMENT ON COLUMN public.user_roles.user_id IS 'Reference to auth.users table';
COMMENT ON COLUMN public.user_roles.role IS 'User role: admin (full access) or operator (limited access)';

-- Create machine_assignments table
-- Maps operators to their assigned vending machines
CREATE TABLE public.machine_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id uuid REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  machine_id text NOT NULL, -- ESP32 device ID from the MDB hardware
  created_at timestamptz DEFAULT now(),
  UNIQUE (operator_id, machine_id)
);

-- Add comments for documentation
COMMENT ON TABLE public.machine_assignments IS 'Maps operators to their assigned vending machines';
COMMENT ON COLUMN public.machine_assignments.operator_id IS 'Reference to auth.users (must be an operator)';
COMMENT ON COLUMN public.machine_assignments.machine_id IS 'ESP32 device ID from the MDB hardware';

-- Enable Row Level Security on both tables
ALTER TABLE public.user_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.machine_assignments ENABLE ROW LEVEL SECURITY;

-- Add comments on RLS
COMMENT ON TABLE public.user_roles IS 'RLS enabled: Users can read own role, admins can manage all';
COMMENT ON TABLE public.machine_assignments IS 'RLS enabled: Operators see assigned machines, admins see all';
