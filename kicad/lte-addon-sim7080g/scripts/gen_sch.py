#!/usr/bin/env python3
"""Generate lte-addon-sim7080g.kicad_sch from design.py.

Every symbol pin gets a short wire stub and a net label (or a no-connect
flag), grouped into labelled blocks. Connectivity therefore comes straight
from design.PARTS and matches the PCB generated by gen_pcb.py.

Usage: python3 scripts/gen_sch.py   (from the project directory)
"""
import os
import re
import sys
import uuid as uuidlib

sys.path.insert(0, os.path.dirname(__file__))
from design import PARTS, PROJECT, SCH_GROUPS  # noqa: E402
from sexpr import block_at, children, find_symbol  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ_DIR = os.path.dirname(HERE)
SYSLIB = os.environ.get("KICAD9_SYMBOL_DIR", "/usr/share/kicad/symbols")
NS = uuidlib.UUID("6b1d6a52-7d0e-4f53-9d3e-0a1b2c3d4e5f")
G = 2.54


def uid(*key):
    return str(uuidlib.uuid5(NS, "/".join(key)))


ROOT = uid("root")


def lib_path(lib):
    if lib == "vmflow_lte":
        return os.path.join(PROJ_DIR, "lib", "vmflow_lte.kicad_sym")
    return os.path.join(SYSLIB, lib + ".kicad_sym")


_lib_cache = {}


def lib_text(lib):
    if lib not in _lib_cache:
        _lib_cache[lib] = open(lib_path(lib)).read()
    return _lib_cache[lib]


def _flatten(txt, name):
    blk = find_symbol(txt, name)
    m = re.match(r'\(symbol "[^"]+"\s*\(extends "([^"]+)"\)', blk)
    if not m:
        return blk
    parent = _flatten(txt, m.group(1))
    pname = re.match(r'\(symbol "([^"]+)"', parent).group(1)
    props = [c for c in children(blk) if c.startswith("(property")]
    keep = [c for c in children(parent) if not c.startswith("(property")]
    keep = [re.sub(r'\(symbol "%s_' % re.escape(pname), '(symbol "%s_' % name, c) for c in keep]
    return '(symbol "%s"\n    %s\n  )' % (name, "\n    ".join(props + keep))


def flattened_symbol(lib_id):
    """Symbol definition text named `lib_id`, with `extends` resolved."""
    lib, name = lib_id.split(":")
    blk = _flatten(lib_text(lib), name)
    return blk.replace('(symbol "%s"' % name, '(symbol "%s"' % lib_id, 1)


def symbol_pins(blk):
    pins = []
    for m in re.finditer(r"\(pin (\w+) \w+\s*\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)\s*"
                         r"\(length ([-\d.]+)\)(.*?)\(name \"([^\"]*)\".*?\(number \"([^\"]*)\"",
                         blk, re.S):
        pins.append(dict(type=m.group(1), x=float(m.group(2)), y=float(m.group(3)),
                         ang=int(float(m.group(4) or 0)), name=m.group(7), num=m.group(8)))
    return pins


def snap(v):
    return round(round(v / G) * G, 2)


def lbl_len(s):
    return len(s) * 1.0 + 2


def main():
    parts = {p[0]: p for p in PARTS}
    syms = {}
    for p in PARTS:
        if p[1] not in syms:
            syms[p[1]] = flattened_symbol(p[1])

    out_items = []
    placed = []
    y_cursor = 30.0
    max_w = 520.0
    for title, refs in SCH_GROUPS:
        out_items.append('(text "%s" (at 20 %.2f 0)\n    (effects (font (size 2.54 2.54) (thickness 0.4) bold) (justify left bottom))\n    (uuid %s)\n  )'
                         % (title, y_cursor, uid("title", title)))
        x_cursor = 25.0
        row_top = y_cursor + 8
        row_h = 0
        for ref in refs:
            ref_, lib_id, value, fp, nets, extra = parts[ref]
            pins = symbol_pins(syms[lib_id])
            xs = [p["x"] for p in pins] or [0]
            ys = [p["y"] for p in pins] or [0]
            # label room on each side
            left = max([lbl_len(nets.get(p["num"], "")) for p in pins if p["ang"] == 0] or [0])
            right = max([lbl_len(nets.get(p["num"], "")) for p in pins if p["ang"] == 180] or [0])
            up = max([lbl_len(nets.get(p["num"], "")) for p in pins if p["ang"] == 270] or [0])
            down = max([lbl_len(nets.get(p["num"], "")) for p in pins if p["ang"] == 90] or [0])
            w = (max(xs) - min(xs)) + left + right + 16
            h = (max(ys) - min(ys)) + up + down + 16
            if x_cursor + w > max_w:
                x_cursor = 25.0
                row_top += row_h + 6
                row_h = 0
            sx = snap(x_cursor + left + 6 - min(xs))
            sy = snap(row_top + up + 8 + max(ys))
            placed.append((ref, lib_id, value, fp, nets, extra, sx, sy, pins, min(ys), max(ys)))
            x_cursor += w
            row_h = max(row_h, h)
        y_cursor = row_top + row_h + 14

    # ---- emit symbols, stubs, labels -------------------------------------
    for (ref, lib_id, value, fp, nets, extra, sx, sy, pins, ymin, ymax) in placed:
        is_pwr = ref.startswith("#")
        in_bom = "no" if (is_pwr or lib_id.startswith("Mechanical:") or lib_id == "Connector:TestPoint") else "yes"
        dnp = "yes" if extra.get("dnp") else "no"
        props = []
        props.append('(property "Reference" "%s" (at %.2f %.2f 0)\n      (effects (font (size 1.27 1.27)))\n    )'
                     % (ref, sx, sy - ymax - 3.5))
        if is_pwr:
            props[-1] = props[-1].replace(" 0)\n      (effects", " 0) (hide yes)\n      (effects", 1)
        props.append('(property "Value" "%s" (at %.2f %.2f 0)\n      (effects (font (size 1.27 1.27)))\n    )'
                     % (value, sx, sy - ymin + 3.5))
        props.append('(property "Footprint" "%s" (at %.2f %.2f 0) (hide yes)\n      (effects (font (size 1.27 1.27)))\n    )'
                     % (fp, sx, sy))
        props.append('(property "Datasheet" "~" (at %.2f %.2f 0) (hide yes)\n      (effects (font (size 1.27 1.27)))\n    )' % (sx, sy))
        if extra.get("mpn"):
            props.append('(property "MPN" "%s" (at %.2f %.2f 0) (hide yes)\n      (effects (font (size 1.27 1.27)))\n    )'
                         % (extra["mpn"], sx, sy))
        if extra.get("note"):
            props.append('(property "Note" "%s" (at %.2f %.2f 0) (hide yes)\n      (effects (font (size 1.27 1.27)))\n    )'
                         % (extra["note"], sx, sy))
        pin_lines = "\n    ".join('(pin "%s" (uuid %s))' % (p["num"], uid(ref, "pin", p["num"], str(i)))
                                   for i, p in enumerate(pins))
        out_items.append(
            '(symbol (lib_id "%s") (at %.2f %.2f 0) (unit 1)\n'
            '    (in_bom %s) (on_board %s) (dnp %s)\n'
            '    (uuid %s)\n    %s\n    %s\n'
            '    (instances\n      (project "%s"\n        (path "/%s"\n          (reference "%s") (unit 1)\n        )\n      )\n    )\n  )'
            % (lib_id, sx, sy, in_bom, "no" if is_pwr else "yes", dnp,
               uid(ref, "sym"), "\n    ".join(props), pin_lines, PROJECT, ROOT, ref))

        seen = set()
        for p in pins:
            px, py = round(sx + p["x"], 2), round(sy - p["y"], 2)
            if (px, py) in seen:
                continue
            seen.add((px, py))
            net = nets.get(p["num"])
            if net is None:
                # all pins stacked at this point must be unconnected too
                stacked = [q for q in pins if round(sx + q["x"], 2) == px and round(sy - q["y"], 2) == py]
                stacked_nets = {nets.get(q["num"]) for q in stacked} - {None}
                if stacked_nets:
                    net = stacked_nets.pop()
            if net is None:
                out_items.append('(no_connect (at %.2f %.2f) (uuid %s))' % (px, py, uid(ref, "nc", p["num"])))
                continue
            d = {0: (-1, 0), 180: (1, 0), 90: (0, 1), 270: (0, -1)}[p["ang"]]
            ex, ey = round(px + d[0] * G, 2), round(py + d[1] * G, 2)
            out_items.append('(wire (pts (xy %.2f %.2f) (xy %.2f %.2f))\n    (stroke (width 0) (type default))\n    (uuid %s)\n  )'
                             % (px, py, ex, ey, uid(ref, "w", p["num"])))
            ang, just = {(-1, 0): (180, "right bottom"), (1, 0): (0, "left bottom"),
                         (0, 1): (270, "right bottom"), (0, -1): (90, "left bottom")}[d]
            out_items.append('(label "%s" (at %.2f %.2f %d) (fields_autoplaced)\n    (effects (font (size 1.27 1.27)) (justify %s))\n    (uuid %s)\n  )'
                             % (net, ex, ey, ang, just, uid(ref, "l", p["num"])))

    notes = [
        "LTE add-on module for the MDB ESP32-S3-WROOM-1U board (rev 1.4.x). Plugs into the mainboard's J2 (JTAG socket) with J1 on its bottom side.",
        "J1 pins 1-4 = GPIO42 DETECT, GPIO41 PWRKEY, GPIO40 ESP TX, GPIO39 ESP RX. GPIO41 high = PWRKEY pressed (MODEM_PWRKEY_INVERTED=1).",
        "DETECT: R8 pulls GPIO42 high when the module is plugged in; firmware reads it with the internal pull-down and skips the modem probe without it.",
        "Supply: VBAT comes from the mainboard 3V3 through J1 pin 6 and R1 (0R), as on the mdb-slave-esp32s3-sim7080g board. C1-C6 buffer the TX bursts.",
        "The modem's GNSS input and USB port are not used and left unconnected.",
    ]
    for i, n in enumerate(notes):
        out_items.append('(text "%s" (at 20 %.2f 0)\n    (effects (font (size 1.5 1.5)) (justify left bottom))\n    (uuid %s)\n  )'
                         % (n, y_cursor + 6 + i * 4, uid("note", str(i))))
    page_h = y_cursor + 6 + len(notes) * 4 + 10

    lib_syms = "\n  ".join(syms[k] for k in sorted(syms))
    sch = """(kicad_sch (version 20250114) (generator "eeschema") (generator_version "9.0")

  (uuid %s)

  (paper "User" 560 %.0f)

  (title_block
    (title "LTE add-on SIM7080G for MDB ESP32-S3-WROOM-1U")
    (date "2026-11-07")
    (rev "1.0")
    (company "VMflow / mdb-esp32-cashless")
    (comment 1 "Generated by scripts/gen_sch.py from scripts/design.py - edit design.py, not this file")
  )

  (lib_symbols
  %s
  )

  %s

  (sheet_instances
    (path "/" (page "1"))
  )
)
""" % (ROOT, max(297, page_h), lib_syms, "\n\n  ".join(out_items))
    path = os.path.join(PROJ_DIR, PROJECT + ".kicad_sch")
    open(path, "w").write(sch)
    print("wrote", path, "symbols:", len(placed))


if __name__ == "__main__":
    main()
